test('a world accumulates writes, pauses work and saves one snapshot on stop', t => {
  let now = 0;
  const {store, directory, library} = fixture(t, {now: () => now}), app = store.addDirectory(directory);
  const initialBytes = readFileSync(join(directory, 'initial.sqlite'));
  const session = store.startSession(app.id, app.fingerprint, {record: true, idleStop: false});
  store.enterSession(app.id, session.id, echoStart);
  now = 100;
  const paused = store.controlSession(app.id, session.id, 'pause')!;
  assert.equal(paused.status, 'paused');
  now += 60_000;
  assert.equal(store.getSession(app.id)!.time, paused.time);
  assert.deepEqual(store.getSession(app.id)!.view!.current.记录, []);
  assert.throws(() => store.enterSession(app.id, session.id, echoStart), /已暂停/);
  store.controlSession(app.id, session.id, 'resume');
  store.enterSession(app.id, session.id, {...echoStart, input: {内容: '第二次输入'}});
  now += 6000;
  const current = store.getSession(app.id)!;
  assert.deepEqual(current.view!.current.记录, [echoStart.input, {内容: '第二次输入'}]);
  assert(current.view!.events.some(e => e.packet?.skin));
  assert.equal(store.runs(app.id).length, 0);
  store.controlSession(app.id, session.id, 'stop');
  const saved = store.getRun(session.id);
  assert.equal(saved.recording.status, 'completed');
  assert.equal(saved.recording.initial.记录.length, 0);
  assert.deepEqual(saved.recording.final.记录, current.view!.current.记录);
  assert.equal(saved.recording.events.filter(event => event.node === echoStart.node && event.kind === 'enter').length, 2);
  assert.deepEqual(readFileSync(join(directory, 'initial.sqlite')), initialBytes);
  writeFileSync(join(directory, 'frontend', 'index.html'), '<h1>改过的前台</h1>');
  assert.throws(() => store.startSession(app.id, app.fingerprint, {record: false, idleStop: false}), /目录已变化/);
  assert.match(store.runAsset(session.id, '前台', 'index.html').data.toString(), /原始界面/);
  assert.equal(saved.source, app.source);
  assert.equal(store.runs(app.id).length, 1);
  store.close();
  const reopened = new Store(library);
  try {
    assert.deepEqual(reopened.getRun(session.id), saved);
    assert.match(reopened.runAsset(session.id, '前台', 'index.html').data.toString(), /原始界面/);
  } finally { reopened.close(); }
});
test('initial SQLite is authoritative and invalid tables, fields and rows are not guessed away', t => {
  const {store, directory} = fixture(t), app = store.addDirectory(directory), file = join(directory, 'initial.sqlite');
  const db = new DatabaseSync(file);
  db.prepare('INSERT INTO 记录 VALUES(?)').run('已有记录'); db.close();
  const current = store.get(app.id);
  assert.notEqual(current.fingerprint, app.fingerprint);
  assert.deepEqual(store.getData(app.id).data, {记录: [{内容:'已有记录'}]});
  const session = store.startSession(app.id, current.fingerprint, {record: false, idleStop: false});
  assert.deepEqual(session.view!.current, {记录: [{内容: '已有记录'}]});
  store.controlSession(app.id, session.id, 'stop');
  const invalid = new DatabaseSync(file); invalid.exec('ALTER TABLE 记录 ADD COLUMN 噪音 TEXT'); invalid.close();
  assert.throws(() => store.get(app.id), /列必须/);
});
test('reminders follow running time and idle stop requires opting in', t => {
  let now = 0;
  const minute = 60_000;
  const {store, directory} = fixture(t, {now: () => now});
  const app = store.addDirectory(directory);
  const first = store.startSession(app.id, app.fingerprint, {record: false, idleStop: false});
  now = 10 * minute - 1;
  assert.equal(store.getSession(app.id)!.reminder, false);
  now++;
  const reminder = store.getSession(app.id)!;
  assert.equal(reminder.reminder, true);
  assert.equal(reminder.status, 'running');
  assert.equal(store.controlSession(app.id, first.id, 'continue')!.reminder, false);
  now = 20 * minute;
  assert.equal(store.getSession(app.id)!.reminder, true);
  now = 31 * minute;
  assert.equal(store.getSession(app.id)!.id, first.id);
  store.controlSession(app.id, first.id, 'stop');
  assert.deepEqual(store.runs(app.id), []);

  const second = store.startSession(app.id, app.fingerprint, {record: true, idleStop: true});
  now += 25 * minute;
  store.controlSession(app.id, second.id, 'activity');
  now += 30 * minute - 1;
  assert.equal(store.getSession(app.id)!.status, 'running');
  now++;
  assert.equal(store.getSession(app.id), null);
  assert.equal(store.getRun(second.id).recording.duration, 27.5 * minute);
});
test('speed changes keep the world clock continuous and preserve pause', t => {
  let now = 0;
  const {store, directory} = fixture(t, {now: () => now});
  const app = store.addDirectory(directory);
  const session = store.startSession(app.id, app.fingerprint, {record: false, idleStop: false});
  store.enterSession(app.id, session.id, echoStart);
  now = 600;
  const fast = store.controlSession(app.id, session.id, {speed: 10})!;
  assert.equal(fast.time, 300);
  assert.equal(fast.speed, 10);
  now = 671;
  assert.equal(store.getSession(app.id)!.nextAt, 660);
  now = 672;
  assert.equal(store.controlSession(app.id, session.id, 'pause')!.time, 660);
  assert(store.getSession(app.id)!.view!.events.some(event => event.kind === 'enter' && event.node === '服务/回声'));
  store.controlSession(app.id, session.id, {speed: 0.1});
  now += 1000;
  assert.equal(store.getSession(app.id)!.time, 660);
  store.controlSession(app.id, session.id, 'resume');
  now += 200;
  assert.equal(store.getSession(app.id)!.time, 670);
});
test('world and frontend paths cannot escape their registered directory', t => {
  const {store, directory, root} = fixture(t);
  assert.throws(() => store.addDirectory('relative'), /绝对路径/);
  const file = join(directory, 'world.yaml'), source = readFileSync(file,'utf8');
  writeFileSync(file, source.replace('directory: frontend','directory: ../outside'));
  assert.throws(() => store.addDirectory(directory), /相对目录/);
  writeFileSync(file, source);
  writeFileSync(join(root,'secret.js'),'secret');
  symlinkSync(join(root,'secret.js'),join(directory,'frontend','leak.js'));
  assert.throws(() => store.addDirectory(directory), /符号链接/);
});
