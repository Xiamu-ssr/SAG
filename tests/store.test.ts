import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync, writeFileSync, unlinkSync, symlinkSync} from 'node:fs';
import {join} from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import {Store} from '../server/store';
import {fixture, worldFolder} from './server-fixtures';
import {echoStart} from './fixtures';

test('library holds directory references and reloads source, frontend and initial data on open', t => {
  const {store, directory, root} = fixture(t), app = store.addDirectory(directory);
  assert.equal(app.directory, directory); assert.equal(store.listApps()[0].fableCount, 1);
  assert.equal(store.addDirectory(directory).id, app.id);
  const file = join(directory, 'world.yaml'), original = readFileSync(file, 'utf8');
  writeFileSync(file, original.replace('测试世界', '改名世界'));
  const updated = store.get(app.id);
  assert.equal(updated.name, '改名世界'); assert.notEqual(updated.fingerprint, app.fingerprint);
  assert.equal(updated.source, readFileSync(file, 'utf8'));
  const second = worldFolder(root, '第二世界'); store.addDirectory(second);
  writeFileSync(file, original.replace('测试世界', '第二世界'));
  assert.throws(() => store.get(app.id), /名称已存在/);
  assert(store.listApps().find(a => a.id === app.id)?.error);
});
